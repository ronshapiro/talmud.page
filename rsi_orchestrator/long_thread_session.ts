import {v4 as uuid} from "uuid";
import {Edit} from "../precomputed/ai_edits";
import {AgentBackend} from "./agent_runner";
import {
  extractBase64Images,
  extractBase64ImagesForCritique,
  formatCritiqueImagePlaceholderNote,
  formatGenerationImagePlaceholderNote,
} from "./base64_images";
import {CritiqueOutcome, TranslationCandidate} from "./rashi_tosafot_translation";

export const DEFAULT_MAX_THREAD_TOKENS = 128 * 1024;
export const DEFAULT_MAX_THREAD_TURNS = 10;

export function isLongThreadBackend(backend?: string): boolean {
  return backend === "claude-long-thread" || backend === "agy-long-thread";
}

export function getBaseBackend(backend: AgentBackend): "claude" | "agy" | "ollama" {
  if (backend === "claude-long-thread") return "claude";
  if (backend === "agy-long-thread") return "agy";
  return backend;
}

export function continuationGenerationPrompt(candidate: TranslationCandidate): string {
  const {textWithPlaceholders, images} = extractBase64Images(
    candidate.hebrewSource,
    {ref: candidate.ref},
  );
  const imageNote = formatGenerationImagePlaceholderNote(images);
  return [
    "Next commentary comment to translate and punctuate on this page:",
    `Comment ref: ${candidate.ref}`,
    `Commentator: ${candidate.commentator}`,
    `Current Hebrew text: ${textWithPlaceholders}`,
    ...(imageNote ? [imageNote] : []),
    "",
    "Follow TRANSLATION_TASK instructions and format established above.",
  ].join("\n");
}

export function continuationCritiquePrompt(
  candidate: TranslationCandidate,
  edit: Edit,
): string {
  const {
    originalHebrewWithPlaceholders,
    proposedHebrewWithPlaceholders,
    proposedEnglishWithPlaceholders,
    images,
  } = extractBase64ImagesForCritique(candidate.hebrewSource, edit, candidate.ref);
  const imageNote = formatCritiqueImagePlaceholderNote(images);
  return [
    "Target comment to check:",
    `Comment ref: ${candidate.ref}`,
    `Original Hebrew: ${originalHebrewWithPlaceholders}`,
    `Proposed Hebrew: ${proposedHebrewWithPlaceholders}`,
    `Proposed English: ${proposedEnglishWithPlaceholders}`,
    ...(imageNote ? [imageNote] : []),
    "",
    "Evaluate according to CRITIQUE_TASK instructions and format established above.",
  ].join("\n");
}

export interface LongThreadSessionOptions {
  maximumTokens?: number;
  maximumTurns?: number;
}

export interface SessionInvocationInfo {
  sessionId?: string;
  isResume: boolean;
}

export class LongThreadSessionManager {
  public currentPage?: string;
  public generateSessionId?: string;
  public critiqueSessionId?: string;
  public turnCount = 0;
  public accumulatedTokens = 0;
  public readonly maximumTokens: number;
  public readonly maximumTurns: number;

  constructor(options?: LongThreadSessionOptions) {
    this.maximumTokens = options?.maximumTokens ?? DEFAULT_MAX_THREAD_TOKENS;
    this.maximumTurns = options?.maximumTurns ?? DEFAULT_MAX_THREAD_TURNS;
  }

  public shouldContinue(candidate: TranslationCandidate): boolean {
    return (
      this.generateSessionId !== undefined
      && this.critiqueSessionId !== undefined
      && this.currentPage === candidate.page
      && this.turnCount < this.maximumTurns
      && this.accumulatedTokens < this.maximumTokens
    );
  }

  public prepareGenerateSession(
    candidate: TranslationCandidate,
    backend: AgentBackend,
    hasPriorFeedback: boolean,
  ): SessionInvocationInfo {
    if (this.shouldContinue(candidate) && !hasPriorFeedback) {
      return {
        sessionId: this.generateSessionId,
        isResume: true,
      };
    }

    // Reset sessions if starting fresh or if feedback requires a clean start
    this.reset();
    this.currentPage = candidate.page;

    const baseBackend = getBaseBackend(backend);
    if (baseBackend === "claude") {
      this.generateSessionId = uuid();
      return {
        sessionId: this.generateSessionId,
        isResume: false,
      };
    }

    // For agy, initial session ID is generated by the CLI and captured from response
    return {
      sessionId: undefined,
      isResume: false,
    };
  }

  public recordGenerateResult(sessionId?: string, tokens?: number): void {
    if (sessionId) {
      this.generateSessionId = sessionId;
    }
    if (tokens) {
      this.accumulatedTokens += tokens;
    }
  }

  public prepareCritiqueSession(backend: AgentBackend): SessionInvocationInfo {
    if (this.critiqueSessionId !== undefined) {
      return {
        sessionId: this.critiqueSessionId,
        isResume: true,
      };
    }

    const baseBackend = getBaseBackend(backend);
    if (baseBackend === "claude") {
      this.critiqueSessionId = uuid();
      return {
        sessionId: this.critiqueSessionId,
        isResume: false,
      };
    }

    // For agy, initial session ID is captured from result
    return {
      sessionId: undefined,
      isResume: false,
    };
  }

  public recordCritiqueOutcome(
    outcome: CritiqueOutcome,
    sessionId?: string,
    tokens?: number,
  ): void {
    if (sessionId) {
      this.critiqueSessionId = sessionId;
    }
    if (tokens) {
      this.accumulatedTokens += tokens;
    }

    if (!outcome.verdict.valid) {
      // Negative critique: toss both threads immediately and start over
      this.reset();
      return;
    }

    this.turnCount += 1;
    if (this.turnCount >= this.maximumTurns || this.accumulatedTokens >= this.maximumTokens) {
      // Reached turn or token limit: reset sessions cleanly for the next candidate
      this.reset();
    }
  }

  public reset(): void {
    this.generateSessionId = undefined;
    this.critiqueSessionId = undefined;
    this.turnCount = 0;
    this.accumulatedTokens = 0;
  }
}
